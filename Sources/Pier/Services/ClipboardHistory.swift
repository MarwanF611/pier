import AppKit
import Observation

struct ClipboardItem: Identifiable, Codable, Hashable {
    enum Content: Codable, Hashable {
        case text(String)
        /// A PNG in Pier's clipboard folder, by file name.
        case image(String)
        case files([URL])
    }

    let id: UUID
    var content: Content
    var copiedAt: Date
    /// The app that was in front when it was copied.
    var appBundleID: String?
    var isPinned = false

    /// One line for the list and for search.
    var preview: String {
        switch content {
        case .text(let text): text.trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\t", with: " ")
        case .image: "Image"
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: ", ")
        }
    }
}

/// What was copied recently, so it can be copied again. Kept on this Mac only, in Pier's
/// Application Support folder. Anything a password manager marks as concealed or transient is
/// never recorded.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipboardItem] = []
    private(set) var thumbnails: [UUID: NSImage] = [:]

    private let folder: URL
    private let indexURL: URL
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    /// Unpinned items kept; pinned ones are kept on top of these.
    static let limit = 60
    private static let maxImageBytes = 15_000_000

    /// Markers from nspasteboard.org that password managers and other apps put on what
    /// shouldn't be kept, plus a few apps' own.
    private static let ignoredTypes = Set([
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type",
    ].map { NSPasteboard.PasteboardType($0) })
    private static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal",
    ]

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Pier", isDirectory: true)
        folder = support.appendingPathComponent("Clipboard", isDirectory: true)
        indexURL = support.appendingPathComponent("clipboard.json")
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        load()
    }

    /// The pasteboard has no change notification, so check its change count twice a second.
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
    }

    /// Puts an item back on the pasteboard and moves it to the top.
    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let name):
            if let image = NSImage(contentsOf: folder.appendingPathComponent(name)) { pasteboard.writeObjects([image]) }
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        changeCount = pasteboard.changeCount
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: index)
        moved.copiedAt = .now
        items.insert(moved, at: 0)
        save()
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        discardFiles(of: [item])
        save()
    }

    /// Forgets everything except pinned items.
    func clear() {
        discardFiles(of: items.filter { !$0.isPinned })
        items.removeAll { !$0.isPinned }
        save()
    }

    func imageURL(_ name: String) -> URL { folder.appendingPathComponent(name) }

    // MARK: - Recording

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !types.contains(where: Self.ignoredTypes.contains), !(app.map(Self.ignoredApps.contains) ?? false) else { return }

        // Finder puts a file's name and icon on the pasteboard too, and Pages or Word put a
        // picture of the text, so files win over text, and text over images.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            record(.files(urls), from: app)
        } else if let text = pasteboard.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            record(.text(text), from: app)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= Self.maxImageBytes,
                  let png = Self.png(from: data) {
            let name = "\(UUID().uuidString).png"
            guard (try? png.write(to: folder.appendingPathComponent(name))) != nil else { return }
            record(.image(name), from: app)
        }
    }

    private func record(_ content: ClipboardItem.Content, from app: String?) {
        // Copying the same thing again moves it to the top rather than adding a duplicate.
        var pinned = false
        if let index = items.firstIndex(where: { $0.content == content }) {
            pinned = items.remove(at: index).isPinned
        }
        items.insert(ClipboardItem(id: UUID(), content: content, copiedAt: .now, appBundleID: app, isPinned: pinned), at: 0)

        let unpinned = items.filter { !$0.isPinned }
        if unpinned.count > Self.limit {
            let dropped = Array(unpinned.suffix(from: Self.limit))
            let ids = Set(dropped.map(\.id))
            items.removeAll { ids.contains($0.id) }
            discardFiles(of: dropped)
        }
        save()
    }

    private static func png(from data: Data) -> Data? {
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]) { return data }
        return NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
    }

    // MARK: - Thumbnails and storage

    func thumbnail(for item: ClipboardItem) -> NSImage? {
        guard case .image(let name) = item.content else { return nil }
        if let cached = thumbnails[item.id] { return cached }
        let url = imageURL(name), id = item.id
        Task.detached(priority: .utility) {
            guard let image = WallpaperManager.downsample(url, maxPixel: 160) else { return }
            await MainActor.run { self.thumbnails[id] = image }
        }
        return nil
    }

    private func discardFiles(of removed: [ClipboardItem]) {
        for item in removed {
            thumbnails[item.id] = nil
            if case .image(let name) = item.content { try? FileManager.default.removeItem(at: imageURL(name)) }
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = saved.filter {
            guard case .image(let name) = $0.content else { return true }
            return FileManager.default.fileExists(atPath: imageURL(name).path)
        }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: indexURL, options: .atomic)
    }
}
